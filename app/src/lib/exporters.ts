import {
  filterSummary,
  formatLine,
  formatTime,
  isErrorLike,
  stats,
} from './journal'
import type { Filters, LogRecord } from './journal'

const AI_EXPORT_MAX_LINES = 8000
const JIRA_EXCERPT_LINES = 200
const JIRA_ERROR_LINES = 50

export function buildAiExport(
  records: LogRecord[],
  filters: Filters,
  sourceName: string,
): string {
  const { perUnit, perPrio, min, max } = stats(records)
  const truncated = records.length > AI_EXPORT_MAX_LINES
  const shown = truncated ? records.slice(-AI_EXPORT_MAX_LINES) : records
  const errors = records.filter(isErrorLike)

  const out: string[] = []
  out.push('# Journal Log Analysis Export')
  out.push('')
  out.push('## Context')
  out.push(`- Source archive: \`${sourceName}\``)
  out.push(`- Exported at: ${formatTime(new Date())}`)
  out.push(`- Filters applied: ${filterSummary(filters)}`)
  out.push('')
  out.push('## Summary')
  out.push(`- Total matching entries: ${records.length}`)
  if (min && max) out.push(`- Time span: ${formatTime(min)}  ->  ${formatTime(max)}`)
  out.push(
    `- Entries matching common error keywords / priority <= warning: ${errors.length}`,
  )
  out.push('')
  out.push('### Entries per unit')
  for (const [unit, count] of [...perUnit.entries()].sort((a, b) => b[1] - a[1])) {
    out.push(`- \`${unit}\`: ${count}`)
  }
  out.push('')
  out.push('### Priority distribution')
  for (const [prio, count] of [...perPrio.entries()].sort()) {
    out.push(`- ${prio}: ${count}`)
  }
  out.push('')
  if (errors.length) {
    out.push('### Notable error-like entries (first 30)')
    for (const r of errors.slice(0, 30)) {
      out.push(`- \`${formatTime(r.ts)}\` [${r.unit || '-'}] ${r.message}`)
    }
    out.push('')
  }
  out.push('## Log entries')
  if (truncated) {
    out.push(
      `*Truncated: showing the last ${shown.length} of ${records.length} entries.*`,
    )
    out.push('')
  }
  out.push('```text')
  out.push(...shown.map(formatLine))
  out.push('```')
  out.push('')
  return out.join('\n')
}

export function buildJiraExport(
  records: LogRecord[],
  filters: Filters,
  sourceName: string,
  summary: string,
  description: string,
): string {
  const { perUnit, perPrio, min, max } = stats(records)
  const errors = records.filter(
    (r) => (r.priority !== null && r.priority <= 3) || isErrorLike(r),
  )
  const excerpt = records.slice(-JIRA_EXCERPT_LINES)

  const codeBlock = (lines: string[]) =>
    `{code:text}\n${lines.join('\n')}\n{code}`

  const out: string[] = []
  out.push(`h2. ${summary || 'Journal log analysis'}`)
  out.push('')
  out.push(`*Log source:* {{${sourceName}}}`)
  if (min && max)
    out.push(`*Log time range:* {{${formatTime(min)} -> ${formatTime(max)}}}`)
  out.push(`*Filters applied:* ${filterSummary(filters)}`)
  out.push(`*Total matching entries:* ${records.length}`)
  out.push('')
  if (description.trim()) {
    out.push('h3. Description')
    out.push(description.trim())
    out.push('')
  }

  out.push('h3. Statistics')
  out.push('|| Unit || Entries ||')
  for (const [unit, count] of [...perUnit.entries()].sort((a, b) => b[1] - a[1])) {
    out.push(`| ${unit} | ${count} |`)
  }
  out.push('')
  out.push('|| Priority || Entries ||')
  for (const [prio, count] of [...perPrio.entries()].sort()) {
    out.push(`| ${prio} | ${count} |`)
  }
  out.push('')

  if (errors.length) {
    out.push(
      `h3. Key error entries (first ${Math.min(errors.length, JIRA_ERROR_LINES)} of ${errors.length})`,
    )
    out.push(codeBlock(errors.slice(0, JIRA_ERROR_LINES).map(formatLine)))
    out.push('')
  }

  out.push(`h3. Log excerpt (last ${excerpt.length} entries)`)
  out.push(codeBlock(excerpt.map(formatLine)))
  out.push('')
  out.push('----')
  out.push(`_Generated by Journal Log Analyzer at ${formatTime(new Date())}_`)
  return out.join('\n')
}

export function downloadText(filename: string, text: string) {
  const blob = new Blob([text], { type: 'text/plain;charset=utf-8' })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  a.click()
  URL.revokeObjectURL(url)
}
